/*==============================================================================================

    runtime_service/draw/draw_font.c -- Built-in 5x7 bitmap debug font.

    A tiny, dependency-free system font for the draw library: no atlas, no sampler, no UV, no
    asset pipeline.  Each lit source pixel becomes one solid quad emitted through the existing
    DRAW_MAT_SOLID pipeline, so text works on any host that loads draw -- even with no gui at all.
    This is the gui-less fallback for a perf HUD / diagnostic readout: exact values (the caller
    owns the formatter) at a fraction of gui's cost.

    gui used to carry a font like this before the baked-atlas (.orb_font / FreeType) path replaced
    it; it was dropped there because gui never needed a fallback once real fonts landed.  It is
    reborn here one layer down, where it belongs -- a system font, not a UI widget.

    Scale is a per-call output parameter (1x / 2x / 3x ...): every source pixel maps to a
    scale x scale block, so the same 5x7 glyph renders at any integer (or fractional) size without
    a second asset.  Cost is bounded by chunk-flushing -- a whole run of glyphs accumulates into
    one submit (one draw call, one buffer write) instead of one per pixel, which would blow the
    DRAW_MAX_CALLS / batch budget instantly.

    Glyph encoding: row-major, 7 rows per glyph, low 5 bits used, bit4 = leftmost column.  The
    GR() macro spells each row out as five 0/1 args so the shape is legible in source (the '1's
    ARE the pixel art).  Covers printable ASCII 0x20..0x7E; anything outside that range advances
    like a space.

==============================================================================================*/
