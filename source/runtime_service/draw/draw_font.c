/*==============================================================================================
    Pixel-quad accumulator -- one submit (draw call + buffer write) per chunk, not per pixel.
    Static (single-threaded immediate mode); each pixel is a unit quad, so DRAW_FONT_CHUNK_PX
    pixels use CHUNK*4 verts / CHUNK*6 idx, both well under the batch caps.
==============================================================================================*/

#define DRAW_FONT_CHUNK_PX   256

static draw_vertex_t s_font_verts[ DRAW_FONT_CHUNK_PX * 4 ];
static u16           s_font_idxs [ DRAW_FONT_CHUNK_PX * 6 ];
static u32           s_font_nv;
static u32           s_font_ni;

static void
font_flush( void )
{
    if ( s_font_ni == 0 )
        return;
    draw_submit( s_font_verts, s_font_nv, s_font_idxs, s_font_ni );
    s_font_nv = 0;
    s_font_ni = 0;
}

/* One scale x scale filled block, centre-placed like every other draw primitive. */
static void
font_pixel( f32 px, f32 py, f32 scale, const f32 rgba[ 4 ] )
{
    if ( s_font_nv + 4u > ( u32 )( DRAW_FONT_CHUNK_PX * 4 ) )
        font_flush();

    f32 hw = scale * 0.5f;
    f32 cx = px + hw;
    f32 cy = py + hw;

    u16 base = ( u16 )s_font_nv;
    s_font_verts[ s_font_nv + 0 ] = ( draw_vertex_t ){ cx - hw, cy - hw, 0.0f,
                                                       rgba[0], rgba[1], rgba[2], rgba[3], 0.0f, 0.0f };
    s_font_verts[ s_font_nv + 1 ] = ( draw_vertex_t ){ cx + hw, cy - hw, 0.0f,
                                                       rgba[0], rgba[1], rgba[2], rgba[3], 0.0f, 0.0f };
    s_font_verts[ s_font_nv + 2 ] = ( draw_vertex_t ){ cx + hw, cy + hw, 0.0f,
                                                       rgba[0], rgba[1], rgba[2], rgba[3], 0.0f, 0.0f };
    s_font_verts[ s_font_nv + 3 ] = ( draw_vertex_t ){ cx - hw, cy + hw, 0.0f,
                                                       rgba[0], rgba[1], rgba[2], rgba[3], 0.0f, 0.0f };
    s_font_nv += 4;

    s_font_idxs[ s_font_ni + 0 ] = base + 0;
    s_font_idxs[ s_font_ni + 1 ] = base + 1;
    s_font_idxs[ s_font_ni + 2 ] = base + 2;
    s_font_idxs[ s_font_ni + 3 ] = base + 0;
    s_font_idxs[ s_font_ni + 4 ] = base + 2;
    s_font_idxs[ s_font_ni + 5 ] = base + 3;
    s_font_ni += 6;
}

