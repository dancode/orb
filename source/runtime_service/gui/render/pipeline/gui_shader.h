/*==============================================================================================

    runtime_service/gui/render/pipeline/gui_shader.h -- Embedded SPIR-V for the gui pipeline.

    FROZEN FALLBACK.  These arrays are the zero-cook-step path: render_init prefers the
    cooked bin/shaders/gui.{vs,ps}.oshd pair (from shaders/gui.{vs,ps}.hlsl via
    cook_shaders.bat) and uses these arrays only when that pair is absent.  New shader work
    happens in the HLSL twins; keep this GLSL and the HLSL byte-identical in their push
    constant block and vertex inputs.

    Compiled from shaders/gui.vert and shaders/gui.frag using:
        glslc --target-env=vulkan1.3 gui.vert -o gui.vert.spv
        glslc --target-env=vulkan1.3 gui.frag -o gui.frag.spv

    Push constant block (shared by vert + frag, 88 bytes):
        mat4 mvp; uint tex_idx; uint samp_idx; uint dbg_flat; uint dbg_tint; uint tex_mode;
        float time;

    dbg_flat / dbg_tint drive the debug render views (normal rendering leaves both 0):
        dbg_flat != 0 -- bypass the atlas and output a flat color, so geometry is visible
                         regardless of glyph coverage (the wireframe LINE pipeline, and the
                         per-batch tint view both set this).
        dbg_tint != 0 -- packed RGBA8 batch tint used as that flat color (R = low byte); 0
                         falls back to the vertex color (what the wireframe view uses).

    tex_mode is the SAMPLING MODEL -- what a texel means (gui_tex_mode_t in gui.h, carried in the
    top 2 bits of the command's tex_idx and split out at flush):
        0 GUI_TEX_COVERAGE -- R8 coverage path: the texel's R channel is glyph alpha and the
                         vertex color supplies RGB (fonts, icons, solid fills via white texel).
        1 GUI_TEX_RGBA  -- full RGBA image path: the texel IS the color (scene viewport /
                         arbitrary bindless texture); the vertex color acts as a tint.  The
                         texel arrives LINEAR (_SRGB views hardware-decode at sample time), so
                         only the authored tint is srgb_to_linear'd.
        2 GUI_TEX_SDF   -- distance-field text: 128/255 is ON the outline, and coverage comes
                         from the screen-space derivative (fwidth) rather than the texel, so the
                         AA band is one pixel wide at ANY scale or rotation and no parameter has
                         to carry the scale.  Vertex color supplies RGB, as for coverage.
    The SAMPLER is derived from this value host-side rather than carried, so a model is a texel
    interpretation AND a filtering rule in one number; one spare value remains.  The fragment
    compares the exact model rather than testing non-zero, so a value added later cannot silently
    inherit whichever branch happened to be the fallback.

    The effect band (locations 3/4) carries a per-vertex signed-distance shape -- see the
    gui_draw_vert_t block in gui.h for the whole model.  Mode 0 is "no effect" and every
    primitive that is not an SDF surface writes it, so text / lines / sprites / square fills
    cost one compare in the fragment and are unchanged.  The mode travels per VERTEX rather
    than in a push constant precisely so an effect can never split a draw batch.

    time is that band's clock, and it is the one effect input that belongs in the push constant:
    it is the same number for every shape in the frame, so per-vertex it would tax every glyph to
    repeat itself, and per-draw it costs nothing because the flush writes it once and leaves it.
    Wrapped to GUI_FX_TIME_WRAP by the caller (gui.h).  GUI_FX_PULSE is the first mode to read it,
    and shows the pattern: a time-driven mode re-partitions the parameter bits it already has (rate
    + depth take the 7 that RING spends on `border`) rather than widening the vertex.

    Vertex GLSL (shaders/gui.vert):
        version 450
        push_constant PC { mat4 mvp; uint tex_idx; uint samp_idx; uint dbg_flat; uint dbg_tint;
                           uint tex_mode; float time; } pc;
        location 0 in  vec2 in_pos;
        location 1 in  vec2 in_uv;
        location 2 in  vec4 in_color;      // UNORM4 byte RGBA -> normalized float4
        location 3 in  vec2 in_fx_coord;   // |p| - c, shape-local pixels
        location 4 in  uint in_fx;         // packed effect word
        location 0 out vec4 v_color;
        location 1 out vec2 v_uv;
        location 2 out vec2 v_fx_coord;
        location 3 flat out uint v_fx;     // flat: a bit field must not interpolate
        main: gl_Position = pc.mvp * vec4(in_pos, 0, 1); pass the four varyings through.

    Fragment GLSL (shaders/gui.frag):
        version 450 + GL_EXT_nonuniform_qualifier
        set=0 binding=0 texture2D u_textures[];
        set=0 binding=1 sampler   u_samplers[];
        push_constant PC { mat4 mvp; uint tex_idx; uint samp_idx; uint dbg_flat; uint dbg_tint;
                           uint tex_mode; float time; } pc;
        location 0 in  vec4 v_color;
        location 1 in  vec2 v_uv;
        location 2 in  vec2 v_fx_coord;
        location 3 flat in uint v_fx;
        location 0 out vec4 out_color;
        fx_coverage(): mode = v_fx & 0xF; mode 0 -> 1.0 (early out).  Else unpack
              radius (bits 4..15, 1/8 px), feather (16..24, 1/4 px), border (25..31, 1/8 px);
              q = v_fx_coord;
              d = min(max(q.x, q.y), 0) + length(max(q, 0)) - radius;   // exact inside AND out
              mode 2 (RING): d = |d + border/2| - border/2;
              cov = feather > 0 ? clamp(0.5 - d/feather, 0, 1) : (d <= 0 ? 1 : 0);
              mode 3 (PULSE): rate = bits 25..28 * 1/4 Hz, depth = bits 29..31 / 7;
                              cov *= 1 - depth * (0.5 - 0.5*cos(2*pi * rate * pc.time));
              return cov;
              The min/max interior term is load-bearing: without it the field saturates at
              -radius everywhere inside, so a border wider than the radius fills the whole
              interior and a shadow softer than the radius never reaches full opacity.
        main: if (dbg_flat) out_color = flat(dbg_tint ? dbg_tint : v_color); else
              { vec4 s = texture(sampler2D(u_textures[tex_idx], u_samplers[samp_idx]), v_uv);
                float cov = fx_coverage();
                if (tex_mode == 1) out_color = vec4(s.rgb * srgb_to_linear(v_color.rgb),
                                               s.a * v_color.a * cov);  // texel arrives linear
                else if (tex_mode == 2) {                               // distance field
                    float d = s.r - 128.0/255.0;                        // 128 = on the outline
                    out_color = vec4(srgb_to_linear(v_color.rgb), v_color.a * cov *
                                     clamp(d / max(fwidth(d), 1e-6) + 0.5, 0, 1)); }
                else          out_color = vec4(srgb_to_linear(v_color.rgb),
                                               v_color.a * s.r * cov); }
              The debug views (dbg_flat) bypass fx_coverage: they exist to show the geometry
              actually submitted, and an SDF surface's four quadrant quads are what you want to
              see there.

        Note: the swapchain is a _SRGB format, so colors are authored in sRGB and
        decoded to linear here -- the GPU then blends in linear space and re-encodes
        on store (the standard game-engine color path).  s.r is 1.0 for the white-pixel
        tex (solid color); the R channel of the R8_UNORM font atlas acts as per-glyph
        alpha, multiplied by the vertex color alpha.

==============================================================================================*/

