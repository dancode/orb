/*==============================================================================================

    runtime_service/gui/render/pipeline/gui_shader.h -- Embedded SPIR-V for the gui pipeline.

    FROZEN FALLBACK.  These arrays are the zero-cook-step path: render_init prefers the
    cooked bin/shaders/gui.{vs,ps}.oshd pair (from shaders/gui.{vs,ps}.hlsl via
    cook_shaders.bat) and uses these arrays only when that pair is absent.  New shader work
    happens in the HLSL twins; keep this GLSL and the HLSL byte-identical in their push
    constant block and vertex inputs.

    Compiled from shaders/gui.vert and shaders/gui.frag using:
        glslc --target-env=vulkan1.3 gui.vert -o gui.vert.spv
        glslc --target-env=vulkan1.3 gui.frag -o gui.frag.spv

    Push constant block (shared by vert + frag, 100 bytes):
        mat4 mvp; uint samp_point; uint samp_image; uint dbg_flat; uint dbg_tint; float time;
        uint clip_buf; uint clip_base; uint prim_buf; uint prim_base;

    Everything in it is FLUSH-constant except prim_base, which is per window SLOT: the record
    arena is packed rather than slabbed, so a window's records start wherever they were placed
    and the dispatch walk re-pushes the tail as it crosses a slot boundary.

    dbg_flat / dbg_tint drive the debug render views (normal rendering leaves both 0):
        dbg_flat != 0 -- bypass the atlas and output a flat color, so geometry is visible
                         regardless of glyph coverage (the wireframe LINE pipeline, and the
                         per-batch tint view both set this).
        dbg_tint != 0 -- packed RGBA8 batch tint used as that flat color (R = low byte); 0
                         falls back to the vertex color (what the wireframe view uses).

    THE PRIMITIVE RECORD (set 0, binding 2) is where per-shape constants live.  The vertex carries
    ONE number -- a slot-local record index -- and the fragment resolves the rest with a dependent
    load: shape, modifiers, texture, clip, rect, radii, softness, rotation, parameters, second
    colour.  gui.h (gui_prim_t) is the layout; five vec4 rows, nothing packed, row 0 first because
    it is the only row a glyph or a flat fill reads.

    Why an indirection rather than more vertex bits: a rounded box emits 16 vertices carrying
    byte-identical copies of what is now one record, so the old container taxed every glyph on
    screen to widen any field, which is what forced the bit-packing in the first place.  With the
    record there is no bit budget, so a corner radius is an f32 in pixels and a new parameter is a
    new member.

    The sampling model is the top 4 bits of the record's `tex` field -- what a texel means
    (gui_tex_mode_t in gui.h); the rest of that field is the bindless slot:
        0 GUI_TEX_COVERAGE -- R8 coverage path: the texel's R channel is glyph alpha and the
                         vertex color supplies RGB (fonts, icons, solid fills via white texel).
        1 GUI_TEX_RGBA  -- full RGBA image path: the texel IS the color (scene viewport /
                         arbitrary bindless texture); the vertex color acts as a tint.  The
                         texel arrives LINEAR (_SRGB views hardware-decode at sample time), and
                         so does the tint (the vertex stage decodes it), so the multiply is
                         light times light.
        2 GUI_TEX_SDF   -- distance-field text: 128/255 is ON the outline, and coverage comes
                         from the screen-space derivative (fwidth) rather than the texel, so the
                         AA band is one pixel wide at ANY scale or rotation and no parameter has
                         to carry the scale.  Vertex color supplies RGB, as for coverage.
    The SAMPLER is derived from this value IN THE FRAGMENT rather than carried, so a model is a
    texel interpretation AND a filtering rule in one number; thirteen spare values remain.  The fragment
    compares the exact model rather than testing non-zero, so a value added later cannot silently
    inherit whichever branch happened to be the fallback.  Both sampler slots ride the push
    constant (samp_point / samp_image) and the model selects between them per vertex.

    Because the texture is named per PRIMITIVE rather than per draw call, one draw can mix the
    coverage atlas, the SDF atlas and arbitrary RGBA images -- so the fragment indexes
    u_textures / u_samplers through nonuniformEXT.  That is a correctness requirement, not a hint:
    the index is no longer wave-uniform.

    THE CLIP TABLE (set 0, binding 2, record field `clip`): the clip rect is resolved in the
    FRAGMENT, not by the hardware scissor, so a clip change never opens a draw call either --
    the batch key is the viewport alone.  Each record names an entry, absolute within the frame's
    clip region, of the clip table -- a bindless storage buffer named by pc.clip_buf with
    pc.clip_base at the region origin, constant for the whole flush.  Entries are two vec4s:
    (x0, y0, x1, y1) pixel edges snapped CPU-side to the scissor's old grid, then a corner radius
    -- 0 reproduces the scissor's hard cut exactly, > 0 evaluates the rounded-box field with a
    1 px AA band (the clip a scissor could never express).  pc.clip_buf == 0 (the reserved invalid
    bindless slot) disables clipping entirely: full coverage, so the pipeline works before any
    table is uploaded.

    THE FIELD (record member `field`) is the signed-distance shape the fragment evaluates -- see
    the gui_prim_t block in gui.h for the whole model.  Field 0 is "no effect" and every primitive
    that is not an SDF surface leaves it there, so text / lines / sprites / square fills cost one
    compare in the fragment and are unchanged.  It is 32 bits wide now, not a 4-bit nibble, and it
    is per PRIMITIVE rather than per draw, so an effect can never split a batch.

    Two of the fields are not shapes at all, which is what the member really means -- "what does
    the fragment do here", not "which SDF is this":

        4 GUI_FX_TILE_U    -- acts on the TEXCOORD: multiplies u by `param_a` before the sample.
                         The stored UV is UNORM16X2 and cannot exceed 1, so a dashed line keeps
                         its repeat count in the record and still tiles the atlas stipple row from
                         ONE quad.  It scaled in the vertex stage while the count was a packed
                         word; the multiply is affine and commutes with interpolation, so moving
                         it here is exactly equivalent and spares the vertex stage a record read.

        5 GUI_FX_TEXT_EDGE -- acts on the COLOR, inside the SDF branch: paints a second colour in
                         a band `param_a` pixels outside the glyph boundary (outline / drop
                         shadow) from the same quad, same batch and same texture sample.  Its
                         colour is the record's `col_b`, at full 8-bit precision -- the packed word
                         had to squeeze all four channels to 5 bits.

    Both return full coverage from fx_coverage(); neither adds geometry or a draw call.

        6 GUI_FX_SEG       -- a CAPSULE: the distance to a line segment, minus its half-thickness,
                         so a diagonal stroke is exact at any angle with round caps for free.  It
                         is the one shape that costs TWO quads rather than four, because the fold
                         at the vertex is forced by SUBTRACTING a half-extent and a capsule
                         subtracts on its along-axis only; the across-axis rides signed and the
                         fragment squares it inside length().  It also needs no interior-distance
                         term -- that form is already the exact signed distance in the core.

        7 GUI_FX_ARC / 8 GUI_FX_PIE -- circular sectors in ONE quad.  A circle subtracts no
                         half-extent, so the effect coord is the raw SIGNED offset (CPU-rotated so
                         the bisector points +y) and the sign carries the angle -- which |p| would
                         have erased.  The record carries ra, the tube half-thickness (PIE writes
                         0) and the aperture (radians, HALF the sweep) as param_a/b/c.  No feather:
                         a sector gets a fixed 1 px band (`0.5 - d`).  The fragment routes
                         `field 7..10` into the sector decode, which also serves the two below.

        9 GUI_FX_ARC_DASH / 10 GUI_FX_ARC_GRAD -- the sector variants.  Both emit with
                         GUI_OP_SELF, so the fragment does not consult the texel (coverage forced
                         1) -- a property of the PRIMITIVE, decided at the emit site, which is why
                         it is an op and not part of the field: the same field can still carry
                         real texcoords.  DASH cuts the band by an angular pattern (period in
                         turns and on-duty fraction, in the record's r_tl/r_tr), anchored at the
                         sweep start, edges antialiased in arc-length px.  GRAD sweeps the vertex
                         colour toward `col_b` lerped by angle/aperture -- the gradient a 4-corner
                         colour cannot express.
                         ORDERING TRAP: the RGBA and SDF sampling-model branches early-return with
                         the PLAIN vertex colour, before the GRAD sweep is applied.  Every sector
                         today is emitted on the coverage model, so this cannot fire -- but a
                         future producer stamping ARC_GRAD onto an RGBA/SDF-model record would
                         silently lose its gradient, not glitch loudly.  (The same trap applies to
                         the CHECKER colour pick below.)

        11 GUI_FX_CHECKER / 12 GUI_FX_GRID -- the framebuffer-tiling patterns, self-sampled like
                         the two above: the fragment computes them from gl_FragCoord / SV_Position
                         (exact float pixels; the HALF2 effect coordinate's ulp reaches a full
                         pixel at the corners of a fullscreen backdrop, and backdrops are the
                         shapes that get that big).  Both carry the cell pitch in param_a and a
                         phase that re-anchors the pattern to the shape so it drags with its
                         window.  CHECKER picks between the vertex colour and `col_b` by cell
                         parity; its phase is param_b/param_c, a fraction of the TWO-cell colour
                         period.  GRID returns coverage: a `param_b` px line every cell, 1 px AA
                         band, vertex colour, drawn over nothing; its phase is r_tl/r_tr as a
                         per-axis fraction of one cell, and param_c turns the lattice.  All mods
                         are floor-based (fmod truncates on the negatives a phase shift produces).

    THE OPS (record member `ops`) are the other half of this: post-ops that MODIFY the coverage a
    box-family field already computed, rather than naming a shape of their own.  BAND bends the
    field into a `border` px rim -- every rounded outline; CUT drops the interior -- the elevation
    shadow under floating chrome; INSET runs the falloff inward instead of across -- the inner
    shadow / pressed well; PULSE breathes the result on pc.time; STRIPES cuts GRID on one axis;
    SELF says the primitive is solid colour and the texel is not consulted.  They are a word of
    their own precisely because they are orthogonal to the field: they compose with each other and
    reach GUI_FX_SEG as readily as GUI_FX_BOX -- a stroked capsule costs no field value.  BAND and
    PULSE compose too now; they could not while both spent the same seven bits of a packed word.

    time is the band's clock, and it is the one effect input that belongs in the push constant:
    it is the same number for every shape in the frame, so per-primitive it would repeat itself
    thousands of times, and per-draw it costs nothing because the flush writes it once and leaves
    it.  Wrapped to GUI_FX_TIME_WRAP by the caller (gui.h).  GUI_OP_PULSE is the only reader: a
    time-driven effect re-emits NO geometry and adds NO draw call, only the constant moves.

    Vertex GLSL (shaders/gui.vert):

        version 450
        push_constant PC { ... same block as the fragment ... } pc;

        location 0 in  vec2 in_pos;        // FLOAT2     attrib
        location 1 in  vec2 in_uv;         // UNORM16X2  attrib -> normalized float2
        location 2 in  vec4 in_color;      // UNORM8X4   attrib -> normalized float4
        location 3 in  vec2 in_fx_coord;   // HALF2      attrib -> float2; |p| - c, shape-local px
        location 4 in  uint in_fx;         // DEAD: the record supersedes it
        location 5 in  uint in_tex;        // DEAD: the record supersedes it
        location 6 in  uint in_prim;       // primitive record index, slot-local
        location 0 out vec4 v_color;
        location 1 out vec2 v_uv;
        location 2 out vec2 v_fx_coord;
        location 3 flat out uint v_fx;
        location 4 flat out uint v_tex;
        location 5 flat out uint v_prim;   // flat: an index into a storage buffer, never blended

        srgb_to_linear(c): c <= 0.04045 ? c/12.92 : pow((c + 0.055)/1.055, 2.4)
        main: gl_Position = pc.mvp * vec4(in_pos, 0, 1);

              v_color = vec4(srgb_to_linear(in_color.rgb), in_color.a);   // see the note below
              pass the other varyings through -- this stage is otherwise pure plumbing now.

        Note that FOUR of the attributes are packed in memory and none of them say so here:
        vertex fetch widens normalized and half formats to float before the shader runs.

    Fragment GLSL (shaders/gui.frag):

        version 450 + GL_EXT_nonuniform_qualifier
        set=0 binding=0 texture2D u_textures[];
        set=0 binding=1 sampler   u_samplers[];
        set=0 binding=2 readonly buffer { vec4 data[]; } u_buffers[];   // clip table + records
        push_constant PC { ... mvp, samplers, debug, time, clip_buf/base, prim_buf/base } pc;

        location 0 in  vec4 v_color;
        location 1 in  vec2 v_uv;
        location 2 in  vec2 v_fx_coord;
        location 3 flat in uint v_fx;      // DEAD
        location 4 flat in uint v_tex;     // DEAD
        location 5 flat in uint v_prim;
        location 0 out vec4 out_color;

        The record is fetched ONCE at the top of main and its row 0 held in file-scope globals
        (g_field / g_ops / g_tex, plus g_row for prim_row(n)).  Rows 1..4 are read only inside the
        branches that need them, which is why row 0 carries what every fragment reads: a glyph, a
        flat fill and a debug-view quad each cost exactly one 16-byte load.  The integer row comes
        back through floatBitsToUint -- a reinterpret; the buffer's element type is vec4 because
        that is the one type the bindless array can declare.

        fx_coverage(): fields 0 / 4 / 5 -> 1.0 (early out -- the ones that are not shapes act
              elsewhere).

              fields 7..10 (ARC/PIE and the two self-sampled variants): own decode (ra/tube/aperture
              from row 4, see the sector block above); q = (|x|, y); PIE = max(disc, signed
              radial-edge distance), ARC = annulus cut to the wedge with round caps; return
              clamp(0.5 - ds, 0, 1).  Bounded above so a field past the sector family reaches the
              box decode below.

              Else feather / border come from row 3, and the CORNER RADIUS from row 2 selected by
              the sign of (gl_FragCoord - centre) un-rotated by the record's (rot_cos, rot_sin).
              That is the first piece of the vertex fold to move: which of four radii a fragment
              wants is a property of where it sits, not of which quadrant quad carried it.
              q = v_fx_coord;
              field 6 (SEG): d = length(vec2(max(q.x, 0), q.y)) - radius;  // capsule, no fold on y
              else           d = min(max(q.x, q.y), 0) + length(max(q, 0)) - radius;

              Then the OPS modify whichever of those two arrived:
              OP_BAND  : d = |d + border/2| - border/2;    // the only one that bends d
              cov = feather > 0 ? clamp(0.5 - d/feather, 0, 1) : (d <= 0 ? 1 : 0);
              OP_CUT   : d <= 0 -> cov = 0;                // interior cut away
              OP_INSET : cov = clamp(1 + d/feather,0,1) * clamp(0.5 - d,0,1);  // falloff inward
              OP_PULSE : rate/depth from row 4;
                         cov *= 1 - depth * (0.5 - 0.5*cos(2*pi * rate * pc.time));
              return cov;

              Every pairing composes, and all of them apply to SEG as readily as to BOX.

              The min/max interior term is load-bearing on the BOX form: without it the field
              saturates at -radius everywhere inside, so a border wider than the radius fills the
              whole interior and a shadow softer than the radius never reaches full opacity.  The
              capsule needs no such term -- its form is already exact in the core.

        main: fetch row 0; ccov = clip_coverage(record.clip);
              if (dbg_flat) out_color = dbg_tint ? vec4(srgb_to_linear(unpack(dbg_tint)), a)
                                                : vec4(v_color.rgb, ccov);  // tint is the ONLY
              else                                        // color still decoded in the fragment
              { uint mode = g_tex >> 28, slot = g_tex & 0x0FFFFFFF;   // both FROM THE RECORD
                uint samp = mode == 0 ? pc.samp_point : pc.samp_image;
                vec2 uv = v_uv;  if (g_field == 4) uv.x *= param_a;     // GUI_FX_TILE_U
                vec4 s = texture(sampler2D(u_textures[nonuniformEXT(slot)],
                                           u_samplers [nonuniformEXT(samp)]), uv);
                float cov = fx_coverage() * ccov;
                if (g_ops & OP_SELF) {           // solid colour: the sample above is discarded
                    s = vec4(1);
                    field 10 (ARC_GRAD): vcol = mix(v_color, unpack(col_b), angle/aperture);
                    field 11 (CHECKER):  vcol = parity(SV_Position, cell, phase) ? unpack(col_b)
                                                                                 : v_color; }
                if (mode == 1) out_color = vec4(s.rgb * v_color.rgb,
                                                s.a * v_color.a * cov);  // texel arrives linear
                else if (mode == 2) {                                    // distance field
                    float d = s.r - 128.0/255.0;                         // 128 = on the outline
                    float dpx = d / max(fwidth(d), 1e-6);                // edge distance in PIXELS
                    float fill = clamp(dpx + 0.5, 0, 1);
                    if (g_field == 5) {                                  // GUI_FX_TEXT_EDGE
                        // widen the same threshold by param_a and source-over the fill onto the
                        // band, so the seam is antialiased once and never double-darkens
                        ... out_color = vec4(mix of v_color and col_b); }
                    else out_color = vec4(v_color.rgb, v_color.a * cov * fill); }

                else           out_color = vec4(v_color.rgb, v_color.a * s.r * cov); }
              The debug views (dbg_flat) bypass fx_coverage: they exist to show the geometry
              actually submitted, and an SDF surface's four quadrant quads are what you want to
              see there.

        Note: the swapchain is a _SRGB format, so colors are authored in sRGB and decoded to
        linear -- the GPU then blends in linear space and re-encodes on store (the standard
        game-engine color path).  The decode is in the VERTEX stage, not here: the vertex color
        is per-vertex constant, so doing it per fragment ran three pow() over every pixel of
        every panel to recompute a number that changes four times per quad, and UI is fill-bound.
        The one visible consequence is that a multi-color quad interpolates in linear light --
        bit-identical for the single-color case (fills, text, sprites, SDF surfaces), but
        GUI_CMD_RECT_GRADIENT's midpoint is now the photometric mean and reads lighter.
        s.r is 1.0 for the white-pixel tex (solid color); the R channel of the R8_UNORM font
        atlas acts as per-glyph alpha, multiplied by the vertex color alpha.

==============================================================================================*/

